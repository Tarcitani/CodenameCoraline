"""Writes the generated client/architect/ArchitectAnimations.java from tools/architect_clips.py (called by
tools/generate_architect_assets.py). Rotations are emitted as deltas from BASE (the model bakes BASE into its parts),
positions as raw model-space offsets (pixels, y down) and scales as offsets from 1, which is exactly what the vanilla
ModelPart.offsetRotation / offsetPos / offsetScale targets add."""
from pathlib import Path

import architect_clips as clips
from architect_poses import BASE

OUT = Path(__file__).resolve().parent.parent / "src/main/java/com/codenamecoraline/client/architect/ArchitectAnimations.java"


def f(v):
    r = round(v, 4)
    return f"{r:g}F" if r != int(r) else f"{int(r)}F"


def camel(name):
    return "".join(w.capitalize() for w in name.lower().split("_"))


def write():
    lines = [
        "package com.codenamecoraline.client.architect;",
        "",
        "import com.codenamecoraline.entity.architect.ArchitectAnim;",
        "import java.util.EnumMap;",
        "import java.util.HashMap;",
        "import java.util.Map;",
        "import net.minecraft.client.animation.AnimationChannel;",
        "import net.minecraft.client.animation.AnimationDefinition;",
        "import net.minecraft.client.animation.Keyframe;",
        "import net.minecraft.client.animation.KeyframeAnimations;",
        "import org.joml.Vector3f;",
        "",
        "/**",
        " * GENERATED by tools/generate_architect_assets.py from tools/architect_clips.py: do not edit by hand.",
        " * Keyframes of every Architect clip (spec docs/design/architect.md §7.4, §10, §11, §13, §15). {@link #BASE} is the",
        " * battle idle baked into the model parts (absolute degrees); rotation keys are deltas from it, position keys are",
        " * model-space offsets in pixels (y down) and scale keys are offsets from 1.",
        " */",
        "public final class ArchitectAnimations {",
        "    public static final Map<String, float[]> BASE = new HashMap<>();",
        "    private static final Map<ArchitectAnim, AnimationDefinition> DEFINITIONS = new EnumMap<>(ArchitectAnim.class);",
        "    private static final AnimationChannel.Interpolation SMOOTH = AnimationChannel.Interpolations.CATMULLROM;",
        "    private static final AnimationChannel.Interpolation LINEAR = AnimationChannel.Interpolations.LINEAR;",
        "",
        "    static {",
    ]
    for k in sorted(BASE):
        if k.startswith(("@", "%")):
            continue
        x, y, z = BASE[k]
        if (x, y, z) != (0, 0, 0):
            lines.append(f'        BASE.put("{k}", new float[] {{{f(x)}, {f(y)}, {f(z)}}});')
    for name in clips.CLIPS:
        lines.append(f"        DEFINITIONS.put(ArchitectAnim.{name}, {camel(name)}());")
    lines += [
        "    }",
        "",
        "    private ArchitectAnimations() {}",
        "",
        "    public static AnimationDefinition get(ArchitectAnim anim) {",
        "        return DEFINITIONS.get(anim);",
        "    }",
        "",
        "    /** Keys as (seconds, x, y, z) quadruples. */",
        "    private static Keyframe[] keys(boolean degrees, AnimationChannel.Interpolation interpolation, float... v) {",
        "        Keyframe[] out = new Keyframe[v.length / 4];",
        "        for (int i = 0; i < out.length; i++) {",
        "            float t = v[i * 4];",
        "            Vector3f target = degrees ? KeyframeAnimations.degreeVec(v[i * 4 + 1], v[i * 4 + 2], v[i * 4 + 3])",
        "                    : new Vector3f(v[i * 4 + 1], v[i * 4 + 2], v[i * 4 + 3]);",
        "            out[i] = new Keyframe(t, target, interpolation);",
        "        }",
        "        return out;",
        "    }",
        "",
        "    private static void rot(AnimationDefinition.Builder b, String part, AnimationChannel.Interpolation i, float... v) {",
        "        b.addAnimation(part, new AnimationChannel(AnimationChannel.Targets.ROTATION, keys(true, i, v)));",
        "    }",
        "",
        "    private static void pos(AnimationDefinition.Builder b, String part, AnimationChannel.Interpolation i, float... v) {",
        "        b.addAnimation(part, new AnimationChannel(AnimationChannel.Targets.POSITION, keys(false, i, v)));",
        "    }",
        "",
        "    private static void scale(AnimationDefinition.Builder b, String part, AnimationChannel.Interpolation i, float... v) {",
        "        b.addAnimation(part, new AnimationChannel(AnimationChannel.Targets.SCALE, keys(false, i, v)));",
        "    }",
    ]
    for name, (ticks, loops, smooth, tracks) in clips.CLIPS.items():
        interp = "SMOOTH" if smooth else "LINEAR"
        lines += ["", f"    private static AnimationDefinition {camel(name)}() {{",
                  f"        AnimationDefinition.Builder b = AnimationDefinition.Builder.withLength({f(ticks / 20)});"]
        if loops:
            lines.append("        b.looping();")
        for key, points in tracks.items():
            if key.startswith("@"):
                kind, part = "pos", key[1:]
                vals = [(t, v) for t, v in points]
            elif key.startswith("%"):
                kind, part = "scale", key[1:]
                vals = [(t, tuple(c - 1 for c in v)) for t, v in points]
            else:
                kind, part = "rot", key
                base = BASE.get(key, (0, 0, 0))
                vals = [(t, tuple(v[i] - base[i] for i in range(3))) for t, v in points]
            body = ", ".join(f"{f(t / 20)}, {f(v[0])}, {f(v[1])}, {f(v[2])}" for t, v in vals)
            lines.append(f'        {kind}(b, "{part}", {interp}, {body});')
        lines += ["        return b.build();", "    }"]
    lines += ["}", ""]
    OUT.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    return len(clips.CLIPS)
